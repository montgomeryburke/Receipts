// A small Word (.docx) writer for meeting minutes: headings, paragraphs, bullet lists and simple tables.
// A .docx is a zip of a few XML files; this builds it in the browser (stored, uncompressed), no library needed.

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(bytes) {
  let c = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) c = CRC_TABLE[(c ^ bytes[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** A zip (no compression) from [{name, data: string|Uint8Array}]. */
export function zipStore(files) {
  const enc = new TextEncoder();
  const parts = [];
  const central = [];
  let offset = 0;
  const u16 = (v) => [v & 0xff, (v >>> 8) & 0xff];
  const u32 = (v) => [v & 0xff, (v >>> 8) & 0xff, (v >>> 16) & 0xff, (v >>> 24) & 0xff];
  for (const f of files) {
    const name = enc.encode(f.name);
    const data = typeof f.data === 'string' ? enc.encode(f.data) : f.data;
    const crc = crc32(data);
    const local = new Uint8Array([0x50, 0x4b, 0x03, 0x04, ...u16(20), ...u16(0x0800), ...u16(0), ...u16(0), ...u16(0x21), ...u32(crc), ...u32(data.length), ...u32(data.length), ...u16(name.length), ...u16(0)]);
    parts.push(local, name, data);
    central.push(new Uint8Array([0x50, 0x4b, 0x01, 0x02, ...u16(20), ...u16(20), ...u16(0x0800), ...u16(0), ...u16(0), ...u16(0x21), ...u32(crc), ...u32(data.length), ...u32(data.length), ...u16(name.length), ...u16(0), ...u16(0), ...u16(0), ...u16(0), ...u32(0), ...u32(offset)]), name);
    offset += local.length + name.length + data.length;
  }
  const cdSize = central.reduce((n, p) => n + p.length, 0);
  const end = new Uint8Array([0x50, 0x4b, 0x05, 0x06, ...u16(0), ...u16(0), ...u16(files.length), ...u16(files.length), ...u32(cdSize), ...u32(offset), ...u16(0)]);
  return new Blob([...parts, ...central, end], { type: 'application/zip' });
}

// Characters XML 1.0 doesn't allow (control characters, U+FFFE/U+FFFF, lone surrogates) are dropped.
const x = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c])).replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\ufffe\uffff]|[\ud800-\udbff](?![\udc00-\udfff])|(?<![\ud800-\udbff])[\udc00-\udfff]/g, '');
const run = (text, { bold = false, italic = false } = {}) => `<w:r>${bold || italic ? `<w:rPr>${bold ? '<w:b/>' : ''}${italic ? '<w:i/>' : ''}</w:rPr>` : ''}<w:t xml:space="preserve">${x(text)}</w:t></w:r>`;

/** Builds the document body from blocks: {h1|h2|title|p|bullet: text} or {table: {head: [...], rows: [[...]]}}. */
function body(blocks) {
  return blocks.map((b) => {
    if (b.title != null) return `<w:p><w:pPr><w:pStyle w:val="Title"/></w:pPr>${run(b.title)}</w:p>`;
    if (b.h1 != null) return `<w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr>${run(b.h1)}</w:p>`;
    if (b.h2 != null) return `<w:p><w:pPr><w:pStyle w:val="Heading2"/></w:pPr>${run(b.h2)}</w:p>`;
    if (b.bullet != null) return `<w:p><w:pPr><w:pStyle w:val="ListBullet"/><w:ind w:left="360" w:hanging="240"/></w:pPr>${run('• ')}${run(b.bullet)}</w:p>`;
    if (b.label != null) return `<w:p>${run(`${b.label}: `, { bold: true })}${run(b.text || '')}</w:p>`;
    if (b.note != null) return `<w:p>${run(b.note, { italic: true })}</w:p>`;
    if (b.table) {
      const cell = (t, head) => `<w:tc><w:tcPr><w:tcW w:w="0" w:type="auto"/></w:tcPr><w:p>${run(t, { bold: head })}</w:p></w:tc>`;
      const border = '<w:tblBorders><w:top w:val="single" w:sz="4" w:color="999999"/><w:left w:val="single" w:sz="4" w:color="999999"/><w:bottom w:val="single" w:sz="4" w:color="999999"/><w:right w:val="single" w:sz="4" w:color="999999"/><w:insideH w:val="single" w:sz="4" w:color="999999"/><w:insideV w:val="single" w:sz="4" w:color="999999"/></w:tblBorders>';
      const rows = [`<w:tr>${b.table.head.map((h) => cell(h, true)).join('')}</w:tr>`, ...b.table.rows.map((r) => `<w:tr>${r.map((c) => cell(c, false)).join('')}</w:tr>`)];
      const cols = b.table.head.length || 1;
      const grid = `<w:tblGrid>${Array.from({ length: cols }, () => `<w:gridCol w:w="${Math.floor(10080 / cols)}"/>`).join('')}</w:tblGrid>`;
      return `<w:tbl><w:tblPr><w:tblW w:w="5000" w:type="pct"/>${border}</w:tblPr>${grid}${rows.join('')}</w:tbl><w:p/>`;
    }
    return `<w:p>${run(b.p ?? '')}</w:p>`;
  }).join('');
}

